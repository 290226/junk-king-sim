/**
 * 把点阵拼成内联 SVG。同一行里连续同色的像素会合并成一个 rect，减小 DOM 体积。
 * @param {string} name PIXEL_ART 的键
 * @param {number} size 显示尺寸（px），默认跟随容器
 */
export function pixelIcon(name, size) {
  const rows = PIXEL_ART[name];
  if (!rows) return '';
  const rects = [];
  for (let y = 0; y < rows.length; y++) {
    const row = rows[y];
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === '.' || !PAL[ch]) { x++; continue; }
      let w = 1;
      while (x + w < row.length && row[x + w] === ch) w++;
      rects.push(`<rect x="${x}" y="${y}" width="${w}" height="1" fill="${PAL[ch]}"/>`);
      x += w;
    }
  }
  const dim = size ? ` width="${size}" height="${size}"` : '';
  return `<svg viewBox="0 0 ${GRID} ${GRID}"${dim} shape-rendering="crispEdges" aria-hidden="true">${rects.join('')}</svg>`;
}

export function hasPixel(name) {
  return Object.prototype.hasOwnProperty.call(PIXEL_ART, name);
}

export default pixelIcon;
